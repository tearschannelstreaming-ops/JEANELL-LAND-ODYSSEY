export const getDailyQuestions = (dateStr: string = new Date().toISOString().split('T')[0]): TriviaQuestion[] => {
  // Use day of year or date hash to deterministically pick 3 rotating questions for today
  const seed = dateStr
    .split('-')
    .reduce((acc, part) => acc * 31 + parseInt(part, 10), 7);
  
  const total = HISTORICAL_TRIVIA_QUESTIONS.length;
  const indices: number[] = [];
  
  for (let i = 0; i < 3; i++) {
    let idx = (seed + i * 4) % total;
    while (indices.includes(idx)) {
      idx = (idx + 1) % total;
    }
    indices.push(idx);
  }
  
  return indices.map(idx => HISTORICAL_TRIVIA_QUESTIONS[idx]);
};
