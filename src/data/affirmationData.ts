export const getDailyTurningPoint = (dayOffset = 0): HistoricalTurningPoint => {
  // Rotate smoothly based on the day of year or chosen index
  const now = new Date();
  const dayOfYear = Math.floor(
    (now.getTime() - new Date(now.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24)
  );
  const index = Math.abs((dayOfYear + dayOffset) % HISTORICAL_TURNING_POINTS.length);
  return HISTORICAL_TURNING_POINTS[index];
};
